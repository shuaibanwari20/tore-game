#!/usr/bin/env node
/**
 * sync-modules.mjs — copy the shared rules/bot modules into the Worker
 * bundle as ES modules.
 *
 * ../game.js and ../bots.js (CommonJS) are the SINGLE SOURCE OF TRUTH —
 * the Node server and sim.js use them unchanged. The only difference the
 * Worker needs is the module syntax: `module.exports = { … };` becomes
 * `export { … };`. Everything else is copied byte-for-byte, so the DO
 * runs exactly the rules sim.js verifies.
 *
 * Run:  node scripts/sync-modules.mjs      (also run by build-client.mjs)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(HERE, '..', '..');
const SRC = path.join(HERE, '..', 'src');

function convert(file) {
  const from = path.join(ROOT, file);
  const to = path.join(SRC, file);
  let code = fs.readFileSync(from, 'utf8');
  const re = /module\.exports\s*=\s*\{([\s\S]*?)\};/;
  const m = code.match(re);
  if (!m) throw new Error(file + ': module.exports block not found — cannot sync');
  code = code.replace(re, 'export {$1};');
  const banner =
    '// GENERATED by cloudflare/scripts/sync-modules.mjs from ../' + file + '\n' +
    '// (the CommonJS original is the source of truth — do not edit this copy).\n';
  fs.writeFileSync(to, banner + code);
  console.log('sync-modules: ' + file + ' -> src/' + file + ' (' + code.length + ' chars)');
}

convert('game.js');
convert('bots.js');
convert('social-core.js');
